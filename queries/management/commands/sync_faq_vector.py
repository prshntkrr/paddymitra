"""
sync_faq_vector
===============
Mirror the FAQ table into the catalogue's vector DB as ONE synthetic document,
so every approved FAQ answer is retrievable as a chunk — not just the ones that
happened to come from an ingested source sheet.

WHY
---
The FAQ table is checked first and served verbatim (queries/services/faq.py), but
that only fires when a question matches an entry closely enough to clear the
decisive-token guard. When it does NOT (a loosely worded or partial question), the
pipeline falls back to RAG — and anything that lives ONLY in the FAQ table is then
invisible, because it was never embedded into Chroma. The two Q&A sheets were the
exception (they were ingested as documents 87/88), so their answers had recall;
hand-added and feedback-promoted FAQs did not.

This command builds a single "FAQ" document from every active FAQ row, cached by
content hash exactly like the other clean-rendered sources, so `build_vector_db`
embeds it. Re-run it whenever the FAQ set changes; it is idempotent (one document,
rewritten in place). Pass --replace-sheets to detach the now-redundant source Q&A
sheets so their answers are not duplicated in retrieval.

    python manage.py sync_faq_vector --replace-sheets --rebuild
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import json
import os

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from catalogues.models import Catalogue
from documents.models import Document
from queries.models import FAQ
from queries.services.faq import models_Q_catalogue

# Source Q&A sheets whose questions are all present in the FAQ table; detaching
# them (by title, so it is portable across environments) avoids duplicate chunks.
SHEET_FAQ_TITLES = [
    "Nutrient Management FAQ (127 questions)",
    "Varietal Information FAQ",
]
DOC_TITLE = "Rice Knowledge Base FAQ (all entries)"
FNAME = "Rice-Knowledge-Base-FAQ.md"


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


class Command(BaseCommand):
    help = "Mirror all active FAQ entries into the catalogue vector DB as one document."

    def add_arguments(self, parser):
        parser.add_argument("--catalogue", default="rice-knowledge-base",
                            help="Catalogue slug (default: rice-knowledge-base).")
        parser.add_argument("--replace-sheets", action="store_true",
                            help="Detach the source Q&A sheet documents to avoid duplicate chunks.")
        parser.add_argument("--rebuild", action="store_true",
                            help="Run build_vector_db for the catalogue after syncing.")

    def handle(self, *args, **options):
        try:
            cat = Catalogue.objects.get(slug=options["catalogue"])
        except Catalogue.DoesNotExist:
            raise CommandError(f"Catalogue '{options['catalogue']}' not found.")

        # 1. Build one chunk per active FAQ (this catalogue + global entries).
        faqs = (FAQ.objects.filter(is_active=True)
                .filter(models_Q_catalogue(cat))
                .order_by("id"))
        chunks, md, skipped = [], [f"# {DOC_TITLE}", "",
                                   "*Every active FAQ entry, mirrored into the vector DB so "
                                   "its answer is retrievable even when the FAQ guard declines "
                                   "a verbatim match. Regenerated by `sync_faq_vector`.*", ""], 0
        for faq in faqs:
            q = (faq.question_en or faq.question_local or "").strip()
            a = (faq.answer_en or faq.answer_local or "").strip()
            if not q or not a:
                skipped += 1
                continue
            chunks.append({"text": f"Q: {q}\nA: {a}",
                           "metadata": {"content_type": "faq", "faq_id": faq.id,
                                        "origin": "faq_sync", "summary": True}})
            md.append(f"**Q{len(chunks)}. {q}**")
            md.append("")
            md.append(a)
            md.append("")

        if not chunks:
            raise CommandError("No active FAQ entries with both a question and an answer.")

        # 2. Write the document file (its hash is the cache key) + a summaries copy.
        media_docs = os.path.join(settings.MEDIA_ROOT, "documents")
        os.makedirs(media_docs, exist_ok=True)
        dst = os.path.join(media_docs, FNAME)
        md_text = "\n".join(md) + "\n"
        with open(dst, "w", encoding="utf-8") as fh:
            fh.write(md_text)
        summ = os.path.join(settings.BASE_DIR, "summaries")
        try:
            os.makedirs(summ, exist_ok=True)
            with open(os.path.join(summ, FNAME), "w", encoding="utf-8") as fh:
                fh.write(md_text)
        except Exception:
            pass

        # 3. Cache JSON keyed by the file's content hash.
        cache_dir = getattr(settings, "DOCLING_CACHE_DIR", "")
        if not cache_dir:
            raise CommandError("DOCLING_CACHE_DIR is not configured.")
        os.makedirs(cache_dir, exist_ok=True)
        digest = _sha256(dst)
        payload = {"source": FNAME, "sha256": digest, "origin": "faq_sync",
                   "built_at": _dt.datetime.now().isoformat(timespec="seconds"),
                   "chunk_count": len(chunks), "chunks": chunks}
        cf = os.path.join(cache_dir, f"{digest}.json")
        with open(cf + ".tmp", "w", encoding="utf-8") as fh:
            json.dump(payload, fh, ensure_ascii=False, indent=1)
        os.replace(cf + ".tmp", cf)

        # 4. Document (one, rewritten in place) attached to the catalogue.
        doc, created = Document.objects.get_or_create(
            title=DOC_TITLE,
            defaults={"crop": "Rice", "content_type": "FAQ", "doc_type": "Other",
                      "source": "FAQ table", "geography": "Odisha / India",
                      "summary": "All active FAQ answers, mirrored into the vector DB.",
                      "status": Document.STATUS_PUBLISHED})
        doc.file.name = f"documents/{FNAME}"
        doc.content_type = "FAQ"
        doc.status = Document.STATUS_PUBLISHED
        doc.save()
        cat.documents.add(doc)

        self.stdout.write(self.style.SUCCESS(
            f"{'created' if created else 'updated'} Document id={doc.id} "
            f"'{DOC_TITLE}' — {len(chunks)} FAQ chunks (skipped {skipped} empty), "
            f"cache {digest[:12]}."))

        # 5. Optionally detach the redundant source Q&A sheets.
        if options["replace_sheets"]:
            for title in SHEET_FAQ_TITLES:
                d = cat.documents.filter(title=title).first()
                if d:
                    cat.documents.remove(d)
                    self.stdout.write(f"  detached redundant sheet doc id={d.id} '{title}'.")

        self.stdout.write(f"catalogue documents now: {cat.documents.count()}")

        # 6. Optional rebuild.
        if options["rebuild"]:
            from catalogues.services.vector_store import build_catalogue_vector_db
            self.stdout.write("Rebuilding vector DB...")
            stats = build_catalogue_vector_db(cat)
            self.stdout.write(self.style.SUCCESS(
                f"Done: {stats['documents']} documents -> {stats['chunks']} chunks."))
        else:
            self.stdout.write(self.style.WARNING(
                "Run `manage.py build_vector_db %s` to embed the new chunks." % cat.slug))
